const UNKNOWN = [0x1f, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1f];

function glyph(char) {
  return FONT[char.toUpperCase()] ?? UNKNOWN;
}

/** Width in device pixels of `text` at `scale`, including inter-glyph gaps. */
export function measureText(text, scale = 1, tracking = 1) {
  if (!text.length) return 0;
  return text.length * (GLYPH_W + tracking) * scale - tracking * scale;
}

export function textHeight(scale = 1) {
  return GLYPH_H * scale;
}

/**
 * Draws `text` with its top-left at (x, y). Every pixel is a filled square of
 * `scale` device pixels, so nothing is ever interpolated.
 */
export function drawText(ctx, text, x, y, { scale = 1, color = '#0f380f', tracking = 1 } = {}) {
  ctx.fillStyle = color;
  let cursorX = x;

  for (const char of text) {
    const rows = glyph(char);
    for (let row = 0; row < GLYPH_H; row++) {
      const bits = rows[row];
      if (!bits) continue;
      for (let col = 0; col < GLYPH_W; col++) {
        if (bits & (1 << (GLYPH_W - 1 - col))) {
          ctx.fillRect(cursorX + col * scale, y + row * scale, scale, scale);
        }
      }
    }
    cursorX += (GLYPH_W + tracking) * scale;
  }
  return cursorX - tracking * scale;
}

/** Convenience: draw centred within a box of `width`. */
export function drawTextCentered(ctx, text, boxX, y, width, opts = {}) {
  const w = measureText(text, opts.scale ?? 1, opts.tracking ?? 1);
  return drawText(ctx, text, boxX + Math.round((width - w) / 2), y, opts);
}

/** Convenience: draw right-aligned so its last pixel lands on `rightX`. */
export function drawTextRight(ctx, text, rightX, y, opts = {}) {
  const w = measureText(text, opts.scale ?? 1, opts.tracking ?? 1);
  return drawText(ctx, text, rightX - w, y, opts);
}
